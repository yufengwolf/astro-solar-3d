// scripts/build-hyg.mjs
// 把 HYG Database v3.7 的恒星 CSV 转成银河系场景可用的真实坐标星场。
// 输出 src/data/hyg-stars.js：位置/颜色为 Float32 base64，运行时 atob 解码。
// 坐标链路与 galaxy.js 的 equatorialToGalactic→galacticToScene 完全一致，
// 因此生成的坐标与程序化旋臂点云 (buildGalaxyField) 同源同尺度（银心原点，kpc）。
//
// 数据源：astronexus/HYG-Database (CC BY-SA-4.0)
//   - ra      : 小时制（0–24），需 ×15 转十进制度
//   - dec     : 十进制度
//   - dist    : 秒差距 (pc)，需 /1000 转 kpc
//   - ci      : B−V 颜色指数，用于恒星配色
//   - mag     : 视星等，用于亮度
// 运行：node scripts/build-hyg.mjs   （自动解压 data/raw/hyg_v37.csv.gz，无需预先解压）

import { readFileSync, writeFileSync } from 'fs';
import { gunzipSync } from 'zlib';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const csvGzPath = resolve(__dirname, '../data/raw/hyg_v37.csv.gz');
const outPath = resolve(__dirname, '../src/data/hyg-stars.js');

// ---- 与 galaxy.js 完全一致的银道坐标转换（纯函数，无 three 依赖） ----
const SUN_GALACTIC_POS = [-7.73, 0.02, 2.74]; // 太阳：距银心 8.2 kpc

function equatorialToGalactic(raDeg, decDeg) {
  const a = raDeg * Math.PI / 180, d = decDeg * Math.PI / 180;
  const ap = 192.85948 * Math.PI / 180, dp = 27.12825 * Math.PI / 180;
  const lNCP = 122.93192 * Math.PI / 180;
  const sinB = Math.sin(d) * Math.sin(dp) + Math.cos(d) * Math.cos(dp) * Math.cos(a - ap);
  const b = Math.asin(Math.max(-1, Math.min(1, sinB)));
  const y = Math.cos(d) * Math.sin(a - ap);
  const x = Math.sin(d) * Math.cos(dp) - Math.cos(d) * Math.sin(dp) * Math.cos(a - ap);
  const l = ((lNCP - Math.atan2(y, x)) * 180 / Math.PI % 360 + 360) % 360;
  return [l, b * 180 / Math.PI];
}

function galacticToScene(l, b, d) {
  const S = SUN_GALACTIC_POS;
  const cross = (a, c) => [a[1] * c[2] - a[2] * c[1], a[2] * c[0] - a[0] * c[2], a[0] * c[1] - a[1] * c[0]];
  const norm = (v) => { const m = Math.hypot(...v); return v.map((x) => x / m); };
  const X = norm(S.map((v) => -v));
  const Y = norm(cross([0, 1, 0], X));
  const Z = norm(cross(X, Y));
  const L = l * Math.PI / 180, B = b * Math.PI / 180;
  const u = d * Math.cos(B) * Math.cos(L);
  const v = d * Math.cos(B) * Math.sin(L);
  const w = d * Math.sin(B);
  return [
    +(S[0] + u * X[0] + v * Y[0] + w * Z[0]).toFixed(9),
    +(S[1] + u * X[1] + v * Y[1] + w * Z[1]).toFixed(9),
    +(S[2] + u * X[2] + v * Y[2] + w * Z[2]).toFixed(9),
  ];
}

// ---- B−V 颜色指数 → RGB（近似黑体色温） ----
const BV_STOPS = [
  [-0.3, [0.62, 0.72, 1.00]],
  [0.0, [0.78, 0.85, 1.00]],
  [0.3, [0.95, 0.96, 1.00]],
  [0.6, [1.00, 0.98, 0.90]],
  [1.0, [1.00, 0.85, 0.60]],
  [1.4, [1.00, 0.70, 0.45]],
  [2.0, [1.00, 0.60, 0.40]],
];
function bvToRGB(bv) {
  if (!isFinite(bv)) bv = 0.6;
  if (bv <= BV_STOPS[0][0]) return BV_STOPS[0][1];
  if (bv >= BV_STOPS[BV_STOPS.length - 1][0]) return BV_STOPS[BV_STOPS.length - 1][1];
  for (let i = 0; i < BV_STOPS.length - 1; i++) {
    const [b0, c0] = BV_STOPS[i], [b1, c1] = BV_STOPS[i + 1];
    if (bv >= b0 && bv <= b1) {
      const t = (bv - b0) / (b1 - b0);
      return [c0[0] + (c1[0] - c0[0]) * t, c0[1] + (c1[1] - c0[1]) * t, c0[2] + (c1[2] - c0[2]) * t];
    }
  }
  return [1, 1, 1];
}

// ---- 读 CSV ----
const raw = gunzipSync(readFileSync(csvGzPath)).toString('utf8');
const lines = raw.split('\n');
const header = lines[0].split(',');
const idx = (n) => header.indexOf(n);
const iRa = idx('ra'), iDec = idx('dec'), iDist = idx('dist'), iMag = idx('mag'), iCi = idx('ci');

const pos = [];
const col = [];
let count = 0;
for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  if (!line) continue;
  const f = line.split(',');
  const ra = parseFloat(f[iRa]);
  const dec = parseFloat(f[iDec]);
  const dist = parseFloat(f[iDist]);
  // 过滤：有效距离；排除异常大值（视差负/不可靠 → 负或超大）。
  // 上限 15 kpc 落在银盘真实尺度内：HYG 收录的银河系恒星（Hipparcos+Yale+Gliese）
  // 可靠距离均 < ~10 kpc，更大的基本是视差误差（最大可达 ~200 kpc），会飞出银盘。
  if (!(dist > 0.01) || dist > 15000) continue;
  if (!isFinite(ra) || !isFinite(dec)) continue;

  const raDeg = ra <= 24 ? ra * 15 : ra;           // 小时制 → 十进制度
  const [l, b] = equatorialToGalactic(raDeg, dec);
  const [x, y, z] = galacticToScene(l, b, dist / 1000); // pc → kpc

  const bv = parseFloat(f[iCi]);
  const mag = parseFloat(f[iMag]);
  const [r, g, bl] = bvToRGB(bv);
  // 亮度：亮星突出、暗星仍可见（地板 0.08），避免一片死黑也避免过曝
  const bright = Math.max(0.08, Math.min(1, 1.1 - (isFinite(mag) ? mag : 10) / 12));

  pos.push(x, y, z);
  col.push(r * bright, g * bright, bl * bright);
  count++;
}

const posArr = new Float32Array(pos);
const colArr = new Float32Array(col);
const posB64 = Buffer.from(posArr.buffer).toString('base64');
const colB64 = Buffer.from(colArr.buffer).toString('base64');

const out = `// AUTO-GENERATED by scripts/build-hyg.mjs — do not edit by hand.
// 数据源：HYG Database v3.7 (astronexus/HYG-Database, CC BY-SA-4.0)
// ${count} 颗恒星，坐标单位 kpc、银心为原点（与 galaxy.js galacticToScene 同源）。
// 位置/颜色为 Float32 的 base64，运行时 atob 解码；仅供银河系背景星场使用。
const _posB64 = "${posB64}";
const _colB64 = "${colB64}";
function _b64ToF32(b64) {
  const bin = atob(b64);
  const u = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
  return new Float32Array(u.buffer);
}
export const HYG_COUNT = ${count};
export const HYG_POS = _b64ToF32(_posB64);
export const HYG_COL = _b64ToF32(_colB64);
`;
writeFileSync(outPath, out);
console.log('Wrote ' + count + ' stars (' + posB64.length + ' b64 bytes pos, ' + colB64.length + ' b64 bytes col) -> ' + outPath);
